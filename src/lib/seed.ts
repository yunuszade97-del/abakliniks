// Типы данных

export interface Child {
  id: string;
  firstName: string;
  lastInitial: string;
  ageYears: number;
  ageMonths: number;
  programDuration: string;
  programStart: string;
  lastAssessmentDate: string;
  overallProgress: number;
  curator: string;
  isOverdue: boolean;
  areas: AreaSummary[];
  recentAssessments: RecentAssessment[];
}

export interface AreaSummary {
  code: string;
  name: string;
  current: number;
  total: number;
}

export interface RecentAssessment {
  date: string;
  area: string;
  specialist: string;
  itemCount: number;
  durationMinutes: number;
}

export interface AssessmentItem {
  code: string;
  name: string;
  description: string;
  criteria: string[];
}

export interface HistoricalScore {
  date: string;
  scores: Record<string, number>;
}

